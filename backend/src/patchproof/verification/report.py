"""Human-readable Markdown verification report for a finished run."""

from __future__ import annotations

from datetime import UTC, datetime

from ..schemas import Run, TestRun

_PROVENANCE = {
    "live_model": "Live BharatCode model response",
    "user_supplied": "Supplied by the user",
    "scripted_example": "Scripted example patch (authored by PatchProof maintainers, not model output)",
    "benchmark_fixture": "Benchmark fixture (authored, not model output)",
}


def _ts(t: float | None) -> str:
    return datetime.fromtimestamp(t, UTC).strftime("%Y-%m-%d %H:%M:%S UTC") if t else "-"


def _run_table(runs: list[TestRun]) -> list[str]:
    lines = ["| Run | Sandbox | Health | Passed | Failed | Errors | Skipped | Duration |",
             "|---|---|---|---|---|---|---|---|"]
    for r in runs:
        c = r.counts()
        lines.append(f"| {r.label} | {r.sandbox}{'' if r.isolated else ' (not isolated)'} | {r.health.value} | "
                     f"{c['passed']} | {c['failed']} | {c['error']} | {c['skipped']} | {r.duration_s:.2f}s |")
    return lines


def render_markdown(run: Run) -> str:
    v = run.verdict
    out = [
        f"# PatchProof verification report: {run.project_name}",
        "",
        f"- Run ID: `{run.id}`",
        f"- Started: {_ts(run.created_at)}; finished: {_ts(run.finished_at)}",
        f"- Patch source: {run.patch_source.value}",
        f"- Sandbox: {run.sandbox or '-'}{'' if run.sandbox_isolated else ' (NOT isolated)'}",
        "",
        "## Verdict",
        "",
        f"**{v.status.value if v else run.state.upper()}**: {v.headline if v else (run.error or '')}",
        "",
    ]
    if v:
        out += [f"- {r}" for r in v.reasons]
        out += ["", f"_Decided by: {v.decided_by}. Passing tests are evidence for the tested cases only; "
                "they are not a proof of correctness or security._", ""]
    if run.issue:
        out += ["## Reported issue", "", "```text", run.issue, "```", ""]
    out += ["## Baseline (original code)", "", *_run_table(run.baseline_runs), ""]
    if run.baseline:
        out += [f"Reproduction targets: {', '.join(f'`{t}`' for t in run.baseline.targets) or 'none'}", ""]
        out += [f"- {r}" for r in run.baseline.reasons]
        out.append("")
    for a in run.attempts:
        out += [f"## Attempt {a.number}", ""]
        if a.diagnosis:
            d = a.diagnosis
            out += [f"**Diagnosis source:** {_PROVENANCE.get(a.diagnosis_source, a.diagnosis_source)}", "",
                    f"**Summary:** {d.summary}", "", f"**Root cause (AI reasoning, not evidence):** {d.root_cause}", ""]
            if d.evidence:
                out += ["**Cited evidence:**", *[f"- `{e.file}` {e.lines or ''}: {e.observation}" for e in d.evidence], ""]
            if d.potential_regressions:
                out += ["**Possible regressions noted by the model:**", *[f"- {x}" for x in d.potential_regressions], ""]
            if d.additional_tests:
                out += ["**Suggested additional tests:**", *[f"- {x}" for x in d.additional_tests], ""]
            out += [f"**Model confidence:** {d.confidence} ({d.confidence_explanation}). Model confidence is not proof.", ""]
        elif a.patch:
            out += [f"**Patch source:** {_PROVENANCE.get(a.patch.provenance, a.patch.provenance)}", ""]
        for call in a.model_calls:
            out.append(f"- Model call ({call.purpose}): {call.model}, {call.latency_ms} ms, "
                       f"tokens={call.total_tokens or '-'}, finish={call.finish_reason or '-'}, request_id={call.request_id or '-'}")
        if a.model_calls:
            out.append("")
        if a.error:
            out += [f"**Error:** {a.error}", ""]
        if a.patch:
            if a.patch.policy_findings:
                out += ["**Patch policy findings:**", *[f"- [{f.severity}] {f.rule}: {f.message}" for f in a.patch.policy_findings], ""]
            if a.patch.diff:
                out += ["**Patch (exact diff applied):**", "", "```diff", a.patch.diff.rstrip(), "```", ""]
        if a.candidate_runs:
            out += ["**Candidate runs:**", "", *_run_table(a.candidate_runs), ""]
        if a.verdict:
            out += [f"**Attempt verdict:** {a.verdict.status.value}: {a.verdict.headline}", ""]
    if v and v.comparison:
        out += ["## Test-by-test comparison", "", "| Test | Target | Baseline | Candidate | Result |", "|---|---|---|---|---|"]
        for c in v.comparison:
            out.append(f"| `{c.nodeid}` | {'yes' if c.is_target else ''} | {c.baseline} | {c.candidate} | {c.category.value} |")
        out.append("")
    if run.disclosures:
        out += ["## Disclosures", "", *[f"- {d}" for d in run.disclosures], ""]
    out += ["---", "Generated by PatchProof AI. Raw test logs are included in the JSON export."]
    return "\n".join(out) + "\n"
